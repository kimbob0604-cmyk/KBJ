# 본문이 구획 줄(`[p002] @계정`)을 흉내 내는 자리. 줄머리의 `[pNNN]`·`[fNNN]`·
# `@핸들` 이다. 수집은 키워드 검색이라 누구의 글이든 들어오고, 본문에 개행 뒤
# 가짜 구획 줄을 넣으면 프롬프트 안에서 진짜 블록과 글자 모양이 같아진다 —
# ① 이 그 문장을 남의(신뢰 계정) 말로 배정하면 `└` 줄에 그 계정이 실린다.
# 수치가 없는 문장이면 3-3 이 잡을 것이 없다(그 문장은 공격자 게시물에 실제로
# 있으므로 1번 검사를 통과한다). 그래서 프롬프트를 만들 때 줄머리를 한 칸
# 들여쓴다 — 본문 글자는 지우지 않는다(검증이 원문과 대조하므로).
FORGE = re.compile(r'(?m)^[ \t]*(?=(?:\[[pfv]\d)|@[A-Za-z0-9])')

# 건수로 셀 때는 **구획 키 모양**만 센다. 줄머리 `@핸들` 은 보통 게시물에도 흔해서,
# 그것까지 세면 결손 줄이 '흉내 N건' 을 과장해 단정한다 (CLAUDE.md 2장 1번).
FORGE_KEY = re.compile(r'(?m)^[ \t]*\[[pfv]\d+\]')


def defuse(text):
    """본문의 줄머리 구획 흉내를 무력화한다. 반환 (본문, 들여쓴 줄 수)."""
    t = str(text or '')
    n = len(FORGE.findall(t))
    return (FORGE.sub(' ', t), n) if n else (t, 0)


def forged(rows):
    """구획 키를 흉내 낸 게시물 수. 결손·verify.json 에 건수를 남긴다."""
    return sum(1 for _k, _a, text in rows if FORGE_KEY.search(str(text or '')))


def posts_block(rows):
    """`[키] @계정` + 본문. 본문은 원문 그대로 넣는다 — 검증이 이 문자열과 대조한다.

    본문을 구획 기호(`---`)로 감싸지 않는다. 게시물이 그 기호를 쓰면 경계가
    흐려지므로, 키 줄을 경계로 쓰고 본문 안 개행은 그대로 둔다. 다만 본문의
    **줄머리** 구획 흉내는 `defuse` 로 한 칸 들여쓴다 — 진짜 구획 줄만 열 0 에서
    시작하게 하는 것이 목적이고, 글자를 지우지 않으므로 검증 대조는 그대로다.
    """
    out = []
    for key, account, text in rows:
        out.append(f'[{key}] @{account}\n{defuse(text)[0]}')
    return '\n\n'.join(out)


def facts_block(rows):
    """④ 입력. `[키] 사실 줄`."""
    return '\n'.join(f'[{k}] {t}' for k, t in rows)
